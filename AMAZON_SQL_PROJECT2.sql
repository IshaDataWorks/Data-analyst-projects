/* PROBLEM 7] Calculate the customer lifetime value (CLTV) for each customer and 
rank customers based on their CLTV. */

SELECT 
c.customer_id,
c.first_name,
c.last_name,
ROUND(SUM(oi.quantity * oi.price_per_unit), 2) as CLTV,
RANK() OVER(
ORDER BY SUM(oi.quantity * oi.price_per_unit) DESC) as r
FROM order_items oi
JOIN orders o
ON oi.order_id = o.order_id 
JOIN customers c 
ON o.customer_id = c.customer_id
GROUP BY c.customer_id,
c.first_name,
c.last_name;

/* INSIGHT - "This query calculates and ranks customers by their Customer Lifetime Value (CLTV), 
enabling the business to identify high-value customers for loyalty programs and targeted marketing campaigns." */

