 /* PROBLEM 11] Classify customers into different segments based on their total purchase amount. */

SELECT
o.customer_id,
ROUND(SUM(oi.quantity * oi.price_per_unit),2) AS total_spending,
CASE
WHEN SUM(oi.quantity * oi.price_per_unit) >= 10000 
THEN 'High Value Customer'
WHEN SUM(oi.quantity * oi.price_per_unit) >= 5000 
THEN 'Medium Value Customer'
ELSE 'Low Value Customer'
END AS customer_segment
FROM orders o
JOIN order_items oi
ON o.order_id = oi.order_id
GROUP BY o.customer_id
ORDER BY total_spending DESC;

/* INSIGHT - Segmented customers based on their spending behavior to identify high-value customers
 and improve targeted marketing strategies. */
 
