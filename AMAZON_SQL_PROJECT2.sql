/* PROBLEM 1] Query the top 10 products by total sales value, including product name, 
total quantity sold, and total sales value.*/
SELECT
p.product_name,
ROUND(SUM(oi.quantity * oi.price_per_unit), 2) as total_sales,
SUM(quantity) as total_quantity
FROM products p 
JOIN order_items oi
ON oi.product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_sales DESC
LIMIT 10;

/* INSIGHT - Identified the top 10 revenue-generating products by analyzing total sales and quantity sold,
 helping the business prioritize inventory planning, promotional campaigns, and revenue optimization.*/
 
 /* PROBLEM 2] Calculate total revenue generated by each product category and include 
the percentage contribution of each category to total revenue.*/

SELECT 
p.category_id,
ROUND(SUM(oi.quantity * oi.price_per_unit),2) as total_revenue,
ROUND( 
(SUM(oi.quantity * oi.price_per_unit) * 100.0) /
SUM(SUM(oi.quantity * oi.price_per_unit)) OVER(), 2
) as revenue_percentage
FROM products p 
JOIN order_items oi
ON oi.product_id = p.product_id
GROUP BY p.category_id 
ORDER BY total_revenue DESC;

/* INSIGHT This query identifies the total revenue generated by each product category and its percentage contribution to overall sales,
 helping the business recognize the most profitable categories. */
 
 /* PROBLEM 3] Compute the average order value (AOV) for each customer and include 
only customers with more than 5 orders. */

SELECT 
customer_id,
order_id,
ROUND(AVG(order_id),2) as avg_order_value
FROM orders o
WHERE order_id > 5
GROUP BY customer_id,
order_id;

/* INSIGHT - "Filters orders with IDs greater than 5 and
 returns each customer's order along with its corresponding order ID" */
 
 /* PROBLEM 4] Query monthly total sales over the past year and display the current 
month’s sales along with the previous month’s sales. */
WITH monthly_sales AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS month,
        SUM(oi.quantity * oi.price_per_unit) AS current_month_sales
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.order_status = 'Completed'
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
)
SELECT
    month,
    ROUND(current_month_sales, 2) AS current_month_sales,
    ROUND(
        LAG(current_month_sales) OVER (
            ORDER BY month
        ), 2
    ) AS previous_month_sales
FROM monthly_sales
ORDER BY month;


/* INSIGHT - "This query identifies customers who have never placed an order,
 enabling the business to target inactive customers with personalized marketing and retention strategies." */
 
